USE BokiDB;
SET NOCOUNT ON;
SET XACT_ABORT ON;

BEGIN TRY
    BEGIN TRAN;

    IF COL_LENGTH('dbo.CAUHOI', 'MUCDO') IS NULL
    BEGIN
        ALTER TABLE dbo.CAUHOI
        ADD MUCDO NVARCHAR(20) NOT NULL
            CONSTRAINT DF_CAUHOI_MUCDO DEFAULT (N'TrungBinh');
    END;

    IF COL_LENGTH('dbo.CAUHOI', 'TRANGTHAI') IS NULL
    BEGIN
        ALTER TABLE dbo.CAUHOI
        ADD TRANGTHAI NVARCHAR(20) NOT NULL
            CONSTRAINT DF_CAUHOI_TRANGTHAI DEFAULT (N'Active');
    END;

    IF NOT EXISTS (
        SELECT 1
        FROM sys.check_constraints
        WHERE name = 'CK_CAUHOI_MUCDO'
          AND parent_object_id = OBJECT_ID('dbo.CAUHOI')
    )
    BEGIN
        EXEC(N'ALTER TABLE dbo.CAUHOI ADD CONSTRAINT CK_CAUHOI_MUCDO CHECK (MUCDO IN (N''De'', N''TrungBinh'', N''Kho''));');
    END;

    IF NOT EXISTS (
        SELECT 1
        FROM sys.check_constraints
        WHERE name = 'CK_CAUHOI_TRANGTHAI'
          AND parent_object_id = OBJECT_ID('dbo.CAUHOI')
    )
    BEGIN
        EXEC(N'ALTER TABLE dbo.CAUHOI ADD CONSTRAINT CK_CAUHOI_TRANGTHAI CHECK (TRANGTHAI IN (N''Active'', N''Draft''));');
    END;

    IF OBJECT_ID('dbo.DETHI', 'U') IS NULL
    BEGIN
        CREATE TABLE dbo.DETHI
        (
            MADETHI INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_DETHI PRIMARY KEY,
            TENDETHI NVARCHAR(255) NOT NULL,
            THOILUONGPHUT INT NOT NULL,
            SOCAU INT NOT NULL,
            TRANGTHAI NVARCHAR(20) NOT NULL CONSTRAINT DF_DETHI_TRANGTHAI DEFAULT (N'Draft'),
            NGAYMO DATETIME NULL,
            NGAYDONG DATETIME NULL,
            NGAYTAO DATETIME NOT NULL CONSTRAINT DF_DETHI_NGAYTAO DEFAULT (GETDATE()),
            NGAYSUA DATETIME NOT NULL CONSTRAINT DF_DETHI_NGAYSUA DEFAULT (GETDATE()),
            MATAIKHOAN_TAO INT NOT NULL,
            CONSTRAINT CK_DETHI_TRANGTHAI CHECK (TRANGTHAI IN (N'Draft', N'Published', N'Closed')),
            CONSTRAINT CK_DETHI_THOILUONG CHECK (THOILUONGPHUT > 0),
            CONSTRAINT CK_DETHI_SOCAU CHECK (SOCAU > 0),
            CONSTRAINT FK_DETHI_TAIKHOAN FOREIGN KEY (MATAIKHOAN_TAO) REFERENCES dbo.TAIKHOAN(MATAIKHOAN)
        );
    END;

    IF OBJECT_ID('dbo.DETHI_MONHOC', 'U') IS NULL
    BEGIN
        CREATE TABLE dbo.DETHI_MONHOC
        (
            MADETHI INT NOT NULL,
            MAMONHOC INT NOT NULL,
            CONSTRAINT PK_DETHI_MONHOC PRIMARY KEY (MADETHI, MAMONHOC),
            CONSTRAINT FK_DETHI_MONHOC_DETHI FOREIGN KEY (MADETHI) REFERENCES dbo.DETHI(MADETHI),
            CONSTRAINT FK_DETHI_MONHOC_MONHOC FOREIGN KEY (MAMONHOC) REFERENCES dbo.MONHOC(MAMONHOC)
        );
    END;

    IF OBJECT_ID('dbo.DETHI_LOP', 'U') IS NULL
    BEGIN
        CREATE TABLE dbo.DETHI_LOP
        (
            MADETHI INT NOT NULL,
            MALOP INT NOT NULL,
            CONSTRAINT PK_DETHI_LOP PRIMARY KEY (MADETHI, MALOP),
            CONSTRAINT FK_DETHI_LOP_DETHI FOREIGN KEY (MADETHI) REFERENCES dbo.DETHI(MADETHI),
            CONSTRAINT FK_DETHI_LOP_LOP FOREIGN KEY (MALOP) REFERENCES dbo.LOP(MALOP)
        );
    END;

    IF OBJECT_ID('dbo.DETHI_HOCSINH', 'U') IS NULL
    BEGIN
        CREATE TABLE dbo.DETHI_HOCSINH
        (
            MADETHI INT NOT NULL,
            MAHOCSINH INT NOT NULL,
            NGAYGIAO DATETIME NOT NULL CONSTRAINT DF_DETHI_HOCSINH_NGAYGIAO DEFAULT (GETDATE()),
            CONSTRAINT PK_DETHI_HOCSINH PRIMARY KEY (MADETHI, MAHOCSINH),
            CONSTRAINT FK_DETHI_HOCSINH_DETHI FOREIGN KEY (MADETHI) REFERENCES dbo.DETHI(MADETHI),
            CONSTRAINT FK_DETHI_HOCSINH_HOCSINH FOREIGN KEY (MAHOCSINH) REFERENCES dbo.HOCSINH(MAHOCSINH)
        );
    END;

    IF OBJECT_ID('dbo.DETHI_CAUHOI', 'U') IS NULL
    BEGIN
        CREATE TABLE dbo.DETHI_CAUHOI
        (
            MADETHICAUHOI INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_DETHI_CAUHOI PRIMARY KEY,
            MADETHI INT NOT NULL,
            MACAUHOI INT NOT NULL,
            STT INT NOT NULL,
            CONSTRAINT FK_DETHI_CAUHOI_DETHI FOREIGN KEY (MADETHI) REFERENCES dbo.DETHI(MADETHI),
            CONSTRAINT FK_DETHI_CAUHOI_CAUHOI FOREIGN KEY (MACAUHOI) REFERENCES dbo.CAUHOI(MACAUHOI)
        );
    END;

    IF OBJECT_ID('dbo.DETHI_LANLAM', 'U') IS NULL
    BEGIN
        CREATE TABLE dbo.DETHI_LANLAM
        (
            MALANLAM INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_DETHI_LANLAM PRIMARY KEY,
            MADETHI INT NOT NULL,
            MAHOCSINH INT NOT NULL,
            DIEMSO FLOAT NOT NULL,
            SOCAUDUNG INT NOT NULL,
            TONGSOCAU INT NOT NULL,
            NGAYNOP DATETIME NOT NULL CONSTRAINT DF_DETHI_LANLAM_NGAYNOP DEFAULT (GETDATE()),
            CONSTRAINT CK_DETHI_LANLAM_SOCAU CHECK (SOCAUDUNG >= 0 AND TONGSOCAU > 0 AND SOCAUDUNG <= TONGSOCAU),
            CONSTRAINT FK_DETHI_LANLAM_DETHI FOREIGN KEY (MADETHI) REFERENCES dbo.DETHI(MADETHI),
            CONSTRAINT FK_DETHI_LANLAM_HOCSINH FOREIGN KEY (MAHOCSINH) REFERENCES dbo.HOCSINH(MAHOCSINH)
        );
    END;

    IF OBJECT_ID('dbo.DETHI_LANLAM_CHITIET', 'U') IS NULL
    BEGIN
        CREATE TABLE dbo.DETHI_LANLAM_CHITIET
        (
            MACHITIET INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_DETHI_LANLAM_CHITIET PRIMARY KEY,
            MALANLAM INT NOT NULL,
            MACAUHOI INT NOT NULL,
            MADAPANCHON INT NULL,
            DUNG BIT NOT NULL,
            CONSTRAINT FK_DETHI_LANLAM_CT_LANLAM FOREIGN KEY (MALANLAM) REFERENCES dbo.DETHI_LANLAM(MALANLAM),
            CONSTRAINT FK_DETHI_LANLAM_CT_CAUHOI FOREIGN KEY (MACAUHOI) REFERENCES dbo.CAUHOI(MACAUHOI),
            CONSTRAINT FK_DETHI_LANLAM_CT_DAPAN FOREIGN KEY (MADAPANCHON) REFERENCES dbo.DAPAN(MADAPAN)
        );
    END;

    IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_DETHI_CAUHOI_MADETHI_STT' AND object_id = OBJECT_ID('dbo.DETHI_CAUHOI'))
    BEGIN
        CREATE UNIQUE INDEX UX_DETHI_CAUHOI_MADETHI_STT
            ON dbo.DETHI_CAUHOI(MADETHI, STT);
    END;

    IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_DETHI_CAUHOI_MADETHI_MACAUHOI' AND object_id = OBJECT_ID('dbo.DETHI_CAUHOI'))
    BEGIN
        CREATE UNIQUE INDEX UX_DETHI_CAUHOI_MADETHI_MACAUHOI
            ON dbo.DETHI_CAUHOI(MADETHI, MACAUHOI);
    END;

    IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_DETHI_HOCSINH_MAHOCSINH' AND object_id = OBJECT_ID('dbo.DETHI_HOCSINH'))
    BEGIN
        CREATE INDEX IX_DETHI_HOCSINH_MAHOCSINH
            ON dbo.DETHI_HOCSINH(MAHOCSINH);
    END;

    IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_DETHI_LANLAM_MADETHI_HOCSINH' AND object_id = OBJECT_ID('dbo.DETHI_LANLAM'))
    BEGIN
        CREATE INDEX IX_DETHI_LANLAM_MADETHI_HOCSINH
            ON dbo.DETHI_LANLAM(MADETHI, MAHOCSINH, NGAYNOP DESC);
    END;

    IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_DETHI_LANLAM_CHITIET_MALANLAM' AND object_id = OBJECT_ID('dbo.DETHI_LANLAM_CHITIET'))
    BEGIN
        CREATE INDEX IX_DETHI_LANLAM_CHITIET_MALANLAM
            ON dbo.DETHI_LANLAM_CHITIET(MALANLAM);
    END;

    COMMIT;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0
        ROLLBACK;

    THROW;
END CATCH;
